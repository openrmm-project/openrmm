// Command notices writes THIRD_PARTY_NOTICES: the copyright notices and
// licences of the third-party code OpenRMM ships. That is the Go modules
// compiled into the server, the agent and the remote sidecar on every platform
// they are built for, the Go runtime itself, and the npm packages bundled into
// the console. MIT, BSD, Apache and OFL all ask for their notice to travel
// with a binary distribution; the release, the images and the console carry
// this file for that.
//
//	go run ./cmd/notices          rewrite THIRD_PARTY_NOTICES
//	go run ./cmd/notices -check   fail when it is out of date (CI)
//
// Run `npm ci` in openrmm/ first: the npm licences are read from node_modules.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const output = "THIRD_PARTY_NOTICES"

// The shipped binaries, and every platform one of them is built for. darwin
// needs cgo for the sidecar's capture code, and so for its imports.
var (
	packages = []string{"./cmd/server", "./cmd/agent", "./cmd/rmm-remote"}
	targets  = []struct{ goos, goarch, cgo string }{
		{"linux", "amd64", "0"}, {"linux", "arm64", "0"},
		{"windows", "amd64", "0"}, {"windows", "arm64", "0"},
		{"darwin", "amd64", "1"}, {"darwin", "arm64", "1"},
	}
	licenceFile = regexp.MustCompile(`(?i)^(licen[cs]e|copying|notice)(\.(md|txt))?$`)
)

type component struct {
	name, version, licence string
	files                  []string // licence and notice files, in order
	text                   string   // used when a package ships no licence file
}

func main() {
	check := flag.Bool("check", false, "fail when "+output+" is out of date instead of writing it")
	flag.Parse()

	var out bytes.Buffer
	out.WriteString("Third-party software in OpenRMM\n\n" +
		"OpenRMM is licensed under the GNU AGPL-3.0 (see LICENSE). It includes the\n" +
		"third-party software below, each under its own licence, reproduced here.\n" +
		"Generated by `go run ./cmd/notices`; do not edit by hand.\n")

	goVersion, goRoot, err := goToolchain()
	if err != nil {
		log.Fatal(err)
	}
	section(&out, "Server, agent and remote sidecar (Go)")
	write(&out, component{name: "The Go runtime and standard library", version: goVersion,
		files: []string{filepath.Join(goRoot, "LICENSE")}})
	mods, err := goModules()
	if err != nil {
		log.Fatal(err)
	}
	for _, c := range mods {
		write(&out, c)
	}

	section(&out, "Console (browser)")
	npm, err := npmPackages("openrmm")
	if err != nil {
		log.Fatal(err)
	}
	for _, c := range npm {
		write(&out, c)
	}

	if *check {
		have, err := os.ReadFile(output)
		if err != nil || !bytes.Equal(have, out.Bytes()) {
			log.Fatalf("%s is out of date: run `go run ./cmd/notices` and commit the result", output)
		}
		return
	}
	if err := os.WriteFile(output, out.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}

// goToolchain names the toolchain go.mod pins, rather than whichever Go runs
// this, so the file does not change with the machine that writes it.
func goToolchain() (version, root string, err error) {
	mod, err := os.ReadFile("go.mod")
	if err != nil {
		return "", "", err
	}
	m := regexp.MustCompile(`(?m)^toolchain\s+(\S+)`).FindSubmatch(mod)
	if m == nil {
		return "", "", errors.New("go.mod has no toolchain line")
	}
	r, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return "", "", fmt.Errorf("go env GOROOT: %w", err)
	}
	return string(m[1]), strings.TrimSpace(string(r)), nil
}

// goModules is every module a shipped binary links on any target, with the
// licence files at its root. A module without one stops the run: it is either
// a licence nobody checked or a missing download.
func goModules() ([]component, error) {
	type module struct {
		Path, Version, Dir string
		Main               bool
		Replace            *struct{ Path, Version, Dir string }
	}
	seen := map[string]component{}
	for _, t := range targets {
		cmd := exec.Command("go", append([]string{"list", "-deps", "-json=Module"}, packages...)...)
		cmd.Env = append(os.Environ(), "GOOS="+t.goos, "GOARCH="+t.goarch, "CGO_ENABLED="+t.cgo)
		cmd.Stderr = os.Stderr
		raw, err := cmd.Output()
		if err != nil {
			return nil, fmt.Errorf("go list for %s/%s: %w", t.goos, t.goarch, err)
		}
		dec := json.NewDecoder(bytes.NewReader(raw))
		for {
			var p struct{ Module *module }
			if err := dec.Decode(&p); err == io.EOF {
				break
			} else if err != nil {
				return nil, err
			}
			m := p.Module
			if m == nil || m.Main {
				continue
			}
			version, dir := m.Version, m.Dir
			if m.Replace != nil {
				version, dir = m.Replace.Version, m.Replace.Dir
			}
			if _, ok := seen[m.Path]; ok {
				continue
			}
			files, err := licenceFiles(dir)
			if err != nil || len(files) == 0 {
				return nil, fmt.Errorf("%s %s: no licence file in %q (run `go mod download`)", m.Path, version, dir)
			}
			seen[m.Path] = component{name: m.Path, version: version, files: files}
		}
	}
	return sorted(seen), nil
}

// npmPackages is every package the console's lockfile installs outside
// devDependencies, which is what the build bundles.
func npmPackages(dir string) ([]component, error) {
	raw, err := os.ReadFile(filepath.Join(dir, "package-lock.json"))
	if err != nil {
		return nil, err
	}
	var lock struct {
		Packages map[string]struct {
			Version string
			License any
			Dev     bool
		}
	}
	if err := json.Unmarshal(raw, &lock); err != nil {
		return nil, err
	}
	seen := map[string]component{}
	for key, p := range lock.Packages {
		if key == "" || p.Dev {
			continue
		}
		name := key[strings.LastIndex(key, "node_modules/")+len("node_modules/"):]
		pkgDir := filepath.Join(dir, key)
		licence, _ := p.License.(string)
		c := component{name: name, version: p.Version, licence: licence}
		c.files, err = licenceFiles(pkgDir)
		if err != nil {
			return nil, fmt.Errorf("%s: %w (run `npm ci` in %s)", name, err, dir)
		}
		if len(c.files) == 0 {
			if c.text, err = mitFromSource(pkgDir, licence); err != nil {
				return nil, fmt.Errorf("%s %s: %w", name, p.Version, err)
			}
		}
		seen[name+"@"+p.Version] = c
	}
	return sorted(seen), nil
}

// mitFromSource covers a package that declares MIT but ships no licence file
// (qrcode-generator): its copyright lines come from the header of its main
// file, under the standard MIT text.
func mitFromSource(pkgDir, licence string) (string, error) {
	if licence != "MIT" {
		return "", fmt.Errorf("no licence file, and licence %q is not one this tool can reproduce", licence)
	}
	var pkg struct{ Main string }
	raw, err := os.ReadFile(filepath.Join(pkgDir, "package.json"))
	if err != nil {
		return "", err
	}
	if err := json.Unmarshal(raw, &pkg); err != nil {
		return "", err
	}
	src, err := os.ReadFile(filepath.Join(pkgDir, pkg.Main))
	if err != nil {
		return "", fmt.Errorf("no licence file, and its main file: %w", err)
	}
	var notices []string
	for _, line := range strings.SplitN(string(src), "\n", 40) {
		if i := strings.Index(line, "Copyright"); i >= 0 {
			notices = append(notices, strings.TrimSpace(line[i:]))
		}
	}
	if len(notices) == 0 {
		return "", errors.New("no licence file and no copyright line in its main file")
	}
	return strings.Join(notices, "\n") + "\n\n" + mitText, nil
}

func licenceFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var files []string
	for _, e := range entries {
		if !e.IsDir() && licenceFile.MatchString(e.Name()) {
			files = append(files, filepath.Join(dir, e.Name()))
		}
	}
	sort.Strings(files)
	return files, nil
}

func sorted(m map[string]component) []component {
	list := make([]component, 0, len(m))
	for _, c := range m {
		list = append(list, c)
	}
	sort.Slice(list, func(i, j int) bool {
		if list[i].name != list[j].name {
			return list[i].name < list[j].name
		}
		return list[i].version < list[j].version
	})
	return list
}

func section(out *bytes.Buffer, title string) {
	fmt.Fprintf(out, "\n\n%s\n%s\n", strings.Repeat("#", 78), "# "+title)
}

func write(out *bytes.Buffer, c component) {
	fmt.Fprintf(out, "\n%s\n%s %s", strings.Repeat("=", 78), c.name, c.version)
	if c.licence != "" {
		fmt.Fprintf(out, " (%s)", c.licence)
	}
	fmt.Fprintf(out, "\n%s\n\n", strings.Repeat("-", 78))
	if c.text != "" {
		out.WriteString(c.text)
		return
	}
	for i, f := range c.files {
		raw, err := os.ReadFile(f)
		if err != nil {
			log.Fatal(err)
		}
		if i > 0 {
			fmt.Fprintf(out, "\n--- %s ---\n\n", filepath.Base(f))
		}
		text := strings.ReplaceAll(string(raw), "\r\n", "\n")
		out.WriteString(strings.TrimRight(text, "\n") + "\n")
	}
}

